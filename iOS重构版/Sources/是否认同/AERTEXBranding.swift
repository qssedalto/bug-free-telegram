/// Website-style brand replacement inside wrapping SwiftUI Text.
/// The Xcode build generates AERTEXWordmarkInline.imageset from the same
/// website SVG. The Linux/xtool fallback retains readable plain text.
func AERTEXBrandedText(_ value: String) -> Text {
    let parts = value.components(separatedBy: "AERTEX")
    guard parts.count > 1 else { return Text(value) }
    #if canImport(UIKit)
    let hasArtwork = UIImage(named: "AERTEXWordmarkInline") != nil
    #else
    let hasArtwork = true
    #endif
    guard hasArtwork else { return Text(value) }
    var result = Text(parts[0])
    for part in parts.dropFirst() {
        result = result + Text(Image("AERTEXWordmarkInline")) + Text(part)
    }
    return result
}
